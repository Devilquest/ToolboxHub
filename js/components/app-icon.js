/**
 * Custom element to render centralized SVG icons.
 * @extends HTMLElement
 * @property {string} name - The name of the icon in the catalog.
 * @property {string} [size='1em'] - The width/height of the icon.
 */
class AppIcon extends HTMLElement {
    /**
     * Lists the attributes that should trigger attributeChangedCallback.
     * @returns {string[]}
     */
    static get observedAttributes() {
        return ['name', 'size'];
    }

    /**
     * Creates an instance of AppIcon.
     */
    constructor() {
        super();
        this.attachShadow({ mode: 'open' });
    }

    /**
     * Renders the icon when the element is added to the DOM.
     */
    connectedCallback() {
        this.render();
    }

    /**
     * Rerenders the icon when observed attributes change.
     */
    attributeChangedCallback() {
        this.render();
    }

    /**
     * Generates and injects the SVG and styles into the Shadow DOM.
     */
    render() {
        const name = this.getAttribute('name');
        const icon = ICON_CATALOG[name];

        if (!icon) {
            this.shadowRoot.innerHTML = '';
            return;
        }

        const size = this.getAttribute('size');
        const stroke = icon.stroke ? 'stroke="currentColor"' : '';
        const fill = icon.stroke ? 'fill="none"' : 'fill="currentColor"';
        const strokeWidth = icon.width ? `stroke-width="${icon.width}"` : '';
        const linecap = icon.stroke ? 'stroke-linecap="round" stroke-linejoin="round"' : '';

        this.shadowRoot.innerHTML = `
            <style>
                :host {
                    display: inline-block;
                    vertical-align: middle;
                    line-height: 0;
                    width: ${size ? size : '1em'};
                    height: auto;
                }
                svg {
                    width: 100%;
                    height: auto;
                    display: block;
                    pointer-events: none;
                }
            </style>
            <svg 
                viewBox="${icon.viewBox}" 
                ${fill} 
                ${stroke} 
                ${strokeWidth} 
                ${linecap}
            >
                ${icon.content}
            </svg>
        `;
    }
}

//=============================================
// Component Registration
//=============================================

if (!customElements.get('app-icon')) {
    customElements.define('app-icon', AppIcon);
}

export default AppIcon;
